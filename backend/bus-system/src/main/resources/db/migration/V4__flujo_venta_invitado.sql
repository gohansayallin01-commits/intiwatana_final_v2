-- =============================================================================
-- INTIWATANA - Migracion V4: flujo comercial de compra
-- =============================================================================
-- Habilita el flujo REAL de compra (invitado y presencial) sin pasarela de pago:
--   1. retenciones  -> reserva/hold de asientos con ciclo de vida propio
--   2. asientos     -> columnas retencion_id / retenido_hasta (bloqueo temporal)
--   3. restricciones de integridad que IMPIDEN la doble venta de un asiento
--   4. boletos.qr_imagen_url pasa a TEXT (el data URI base64 del QR supera 500)
--
-- Es ADITIVA y NO destructiva: no borra ni transforma datos existentes.
-- Estados de asiento: reutiliza 'RESERVADO' (ya contemplado en el CHECK de V1).
-- =============================================================================

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SET search_path TO public;

--
-- Name: retenciones; Type: TABLE
--

CREATE TABLE public.retenciones (
    id bigint NOT NULL,
    referencia character varying(40) NOT NULL,
    viaje_id bigint NOT NULL,
    estado character varying(20) DEFAULT 'RETENIDO'::character varying NOT NULL,
    canal character varying(20) DEFAULT 'WEB'::character varying NOT NULL,
    comprador_nombres character varying(150),
    comprador_apellidos character varying(150),
    comprador_documento character varying(15) NOT NULL,
    comprador_telefono character varying(20),
    comprador_email character varying(150),
    cantidad_asientos integer NOT NULL,
    precio_unitario numeric(10,2) NOT NULL,
    total numeric(10,2) NOT NULL,
    asientos_numeros character varying(300),
    metodo_pago_preferido character varying(30),
    idempotency_key character varying(100),
    expira_en timestamp without time zone NOT NULL,
    confirmada_en timestamp without time zone,
    liberada_en timestamp without time zone,
    motivo_liberacion character varying(300),
    observaciones character varying(300),
    confirmada_por_id bigint,
    pago_id bigint,
    activo boolean DEFAULT true NOT NULL,
    created_at timestamp without time zone DEFAULT now() NOT NULL,
    updated_at timestamp without time zone,
    deleted_at timestamp without time zone,
    CONSTRAINT retenciones_estado_check CHECK (((estado)::text = ANY ((ARRAY['RETENIDO'::character varying, 'PENDIENTE_PAGO'::character varying, 'CONFIRMADO'::character varying, 'VENCIDO'::character varying, 'CANCELADO'::character varying])::text[]))),
    CONSTRAINT retenciones_canal_check CHECK (((canal)::text = ANY ((ARRAY['WEB'::character varying, 'CAJERO'::character varying])::text[])))
);

ALTER TABLE public.retenciones ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.retenciones_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.retenciones
    ADD CONSTRAINT retenciones_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.retenciones
    ADD CONSTRAINT retenciones_referencia_key UNIQUE (referencia);

ALTER TABLE ONLY public.retenciones
    ADD CONSTRAINT retenciones_viaje_id_fkey FOREIGN KEY (viaje_id) REFERENCES public.viajes(id);

ALTER TABLE ONLY public.retenciones
    ADD CONSTRAINT retenciones_confirmada_por_id_fkey FOREIGN KEY (confirmada_por_id) REFERENCES public.usuarios(id);

ALTER TABLE ONLY public.retenciones
    ADD CONSTRAINT retenciones_pago_id_fkey FOREIGN KEY (pago_id) REFERENCES public.pagos(id);

--
-- Name: asientos; Type: ALTER (retención temporal de asientos)
--

ALTER TABLE public.asientos
    ADD COLUMN retencion_id bigint,
    ADD COLUMN retenido_hasta timestamp without time zone;

ALTER TABLE ONLY public.asientos
    ADD CONSTRAINT asientos_retencion_id_fkey FOREIGN KEY (retencion_id) REFERENCES public.retenciones(id);

--
-- Name: boletos; Type: ALTER (QR como TEXT)
--

ALTER TABLE public.boletos
    ALTER COLUMN qr_imagen_url TYPE text;

--
-- Name: indices de integridad y rendimiento
--

-- Un asiento sólo puede tener como máximo UN boleto vigente (no cancelado).
-- Los boletos CANCELADOS quedan fuera del índice para permitir revender.
CREATE UNIQUE INDEX uk_boletos_asiento_activo
    ON public.boletos (asiento_id)
    WHERE ((estado)::text <> 'CANCELADO'::text);

-- Idempotencia de creación de reservas: una clave => una sola reserva.
CREATE UNIQUE INDEX uk_retencion_idempotency
    ON public.retenciones (idempotency_key)
    WHERE (idempotency_key IS NOT NULL);

CREATE INDEX idx_retencion_estado_expira
    ON public.retenciones (estado, expira_en);

CREATE INDEX idx_retencion_documento
    ON public.retenciones (comprador_documento);
